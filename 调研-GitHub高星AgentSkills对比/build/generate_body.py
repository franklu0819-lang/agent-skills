def make_table(headers, rows, ratios, align_center_cols=None):
    align_center_cols = align_center_cols or []
    data = [[Paragraph('<b>%s</b>' % h, S['th']) for h in headers]]
    for r in rows:
        data.append([Paragraph(c, S['tdc'] if ci in align_center_cols else S['td'])
                     for ci, c in enumerate(r)])
    t = Table(data, colWidths=[x * AVAIL_W for x in ratios], hAlign='CENTER', repeatRows=1)
    st = [('BACKGROUND', (0, 0), (-1, 0), HEADER_FILL),
          ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
          ('GRID', (0, 0), (-1, -1), 0.5, BORDER),
          ('LEFTPADDING', (0, 0), (-1, -1), 6), ('RIGHTPADDING', (0, 0), (-1, -1), 6),
          ('TOPPADDING', (0, 0), (-1, -1), 5), ('BOTTOMPADDING', (0, 0), (-1, -1), 5)]
    for i in range(1, len(data)):
        st.append(('BACKGROUND', (0, i), (-1, i), colors.white if i % 2 == 1 else TABLE_STRIPE))
    t.setStyle(TableStyle(st))
    return t

def table_block(story, title, headers, rows, ratios, **kw):
    t = make_table(headers, rows, ratios, **kw)
    cap = Paragraph(title, S['caption'])
    if len(rows) <= 8:
        story.append(Spacer(1, 8))
        story.append(KeepTogether([t, cap]))
        story.append(Spacer(1, 8))
    else:
        story.append(Spacer(1, 8))
        story.append(t)
        story.append(cap)
        story.append(Spacer(1, 8))

def callout_row(story, stats):
    n = len(stats)
    cw = (AVAIL_W - 12 * (n - 1)) / n
    cells = []
    for big, lab in stats:
        inner = Table([[Paragraph('<b>%s</b>' % big, S['stat'])],
                       [Paragraph(lab, S['statlab'])]], colWidths=[cw])
        inner.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), CARD_BG), ('BOX', (0, 0), (-1, -1), 1, ACCENT),
            ('TOPPADDING', (0, 0), (-1, 0), 9), ('BOTTOMPADDING', (0, 1), (-1, 1), 9),
            ('VALIGN', (0, 0), (-1, -1), 'MIDDLE')]))
        cells.append(inner)
    wrap = Table([cells], colWidths=[cw + (12 if i < n - 1 else 0) for i in range(n)])
    wrap.setStyle(TableStyle([('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('LEFTPADDING', (0, 0), (-1, -1), 0), ('RIGHTPADDING', (0, 0), (-2, -1), 12),
        ('RIGHTPADDING', (-1, 0), (-1, -1), 0), ('TOPPADDING', (0, 0), (-1, -1), 0),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 0)]))
    story.append(Spacer(1, 6)); story.append(KeepTogether(wrap)); story.append(Spacer(1, 10))

