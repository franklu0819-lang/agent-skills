def table_block(story, caption, header, rows, widths, aligns=None, zebra=True):
    """通用表格：表题注置于表格上方；首列仓库名在斜杠后补断点空格避免字母中间断行"""
    ncol = len(header)
    aligns = aligns or ['L'] * ncol
    total = sum(widths)
    colw = [w / total * AVAIL_W for w in widths]
    data = [[Paragraph(x, S['th']) for x in header]]
    for r in rows:
        cells = list(r)
        if cells and '/' in cells[0]:
            cells[0] = cells[0].replace('/', '/ ').replace('/  ', '/ ')
        rendered = []
        for i, c in enumerate(cells):
            if i == 0 and aligns[i] != 'C':
                rendered.append(Paragraph(c, S['tdslug']))
            else:
                rendered.append(Paragraph(c, S['tdc'] if aligns[i] == 'C' else S['td']))
        data.append(rendered)
    t = Table(data, colWidths=colw, repeatRows=1, hAlign='CENTER')
    style = [
        ('BACKGROUND', (0, 0), (-1, 0), HEADER_FILL),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('TOPPADDING', (0, 0), (-1, -1), 4), ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ('LEFTPADDING', (0, 0), (-1, -1), 5), ('RIGHTPADDING', (0, 0), (-1, -1), 5),
        ('LINEBELOW', (0, 0), (-1, 0), 0.8, HEADER_FILL),
        ('GRID', (0, 0), (-1, -1), 0.4, BORDER),
    ]
    if zebra:
        for i in range(1, len(data)):
            if i % 2 == 0:
                style.append(('BACKGROUND', (0, i), (-1, i), TABLE_STRIPE))
    t.setStyle(TableStyle(style))
    cap = Paragraph(caption, S['caption'])
    if len(rows) > 7:
        story.append(cap); story.append(t)
    else:
        story.append(KeepTogether([cap, t]))

